-- 票 05：不依赖 AI 的导入配方。
--
-- 配方是声明式的：布局 + 表头指纹 + 列映射 + 清洗/校验选项 + 样例与预期结果。
-- 不存可执行脚本；版本表保留每次保存的完整快照，供 06 回退。
-- 软删除沿用票 03 的语义（deleted_at），06 的删除/恢复直接接这一列。

CREATE TABLE import_recipe (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120) NOT NULL UNIQUE,
    layout           VARCHAR(16)  NOT NULL,
    fingerprint_json TEXT         NOT NULL,
    columns_json     TEXT         NOT NULL,
    options_json     TEXT         NOT NULL,
    expected_json    TEXT         NULL,
    sample_json      TEXT         NULL,
    version          INT          NOT NULL DEFAULT 1,
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by       VARCHAR(64)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    last_used_at     TIMESTAMP    NULL,
    deleted_at       TIMESTAMP    NULL
);

CREATE INDEX idx_import_recipe_last_used ON import_recipe (last_used_at);
CREATE INDEX idx_import_recipe_deleted ON import_recipe (deleted_at);

CREATE TABLE import_recipe_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id     BIGINT       NOT NULL,
    version       INT          NOT NULL,
    snapshot_json TEXT         NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    created_by    VARCHAR(64)  NOT NULL,
    CONSTRAINT fk_import_recipe_version_recipe
        FOREIGN KEY (recipe_id) REFERENCES import_recipe (id)
);

CREATE UNIQUE INDEX uk_import_recipe_version ON import_recipe_version (recipe_id, version);
