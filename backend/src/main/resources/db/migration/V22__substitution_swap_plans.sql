-- Phase 9: published-timetable swaps (same-class cycles) and covers.
-- V20/V21 were taken by phase 8; this is the next free number.

ALTER TABLE substitution_request ADD COLUMN type VARCHAR(20) NOT NULL DEFAULT 'COVER';
ALTER TABLE substitution_request ADD COLUMN target_period_id BIGINT;
UPDATE substitution_request SET type = 'COVER';

ALTER TABLE substitution ADD COLUMN type VARCHAR(20) NOT NULL DEFAULT 'COVER';
ALTER TABLE substitution ADD COLUMN plan_id BIGINT;
UPDATE substitution SET type = 'COVER';

CREATE TABLE substitution_plan (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      BIGINT      NOT NULL,
    semester_id     BIGINT      NOT NULL,
    snapshot_hash   VARCHAR(64) NOT NULL,
    ranking_preset  VARCHAR(30) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    impact_days     INT         NOT NULL,
    impact_teachers INT         NOT NULL,
    soft_penalty    INT         NOT NULL,
    cycle_length    INT         NOT NULL,
    same_week       BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP   NOT NULL,
    expires_at      TIMESTAMP   NOT NULL,
    approved_at     TIMESTAMP,
    approved_by     VARCHAR(64),
    CONSTRAINT fk_plan_request FOREIGN KEY (request_id) REFERENCES substitution_request (id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);

CREATE TABLE substitution_plan_move (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id         BIGINT NOT NULL,
    entry_id        BIGINT NOT NULL,
    class_id        BIGINT NOT NULL,
    course_id       BIGINT NOT NULL,
    teacher_id      BIGINT NOT NULL,
    room_id         BIGINT,
    from_period_id  BIGINT NOT NULL,
    from_day_of_week INT   NOT NULL,
    from_period_no  INT    NOT NULL,
    from_date       DATE   NOT NULL,
    to_period_id    BIGINT NOT NULL,
    to_day_of_week  INT    NOT NULL,
    to_period_no    INT    NOT NULL,
    to_date         DATE   NOT NULL,
    move_order      INT    NOT NULL,
    CONSTRAINT fk_move_plan FOREIGN KEY (plan_id) REFERENCES substitution_plan (id) ON DELETE CASCADE
);

CREATE INDEX idx_plan_request ON substitution_plan (request_id);
CREATE INDEX idx_plan_status ON substitution_plan (semester_id, status);
CREATE INDEX idx_plan_move_plan ON substitution_plan_move (plan_id);
CREATE INDEX idx_sub_plan ON substitution (plan_id);
CREATE INDEX idx_sub_type ON substitution (semester_id, type);
