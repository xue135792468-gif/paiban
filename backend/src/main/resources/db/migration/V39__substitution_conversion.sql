-- 票 02（ADR-0030）：历史调代日期转换的确认门与批次留痕。
-- 确认转换是数据切换门：每次经确认的转换生成一条 CONVERTED 批次（与对
-- substitution 行的写入同一个原子事务）；意外失败时用独立事务补一条 FAILED
-- 批次与失败原因，避免随业务回滚一起消失。阻塞记录不落库——预检报告实时
-- 推导，阻塞存在时确认门直接拒绝，原数据保持不变。

CREATE TABLE substitution_conversion (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id          BIGINT      NOT NULL,
    status               VARCHAR(30) NOT NULL,
    legacy_total         INT         NOT NULL,
    converted_count      INT         NOT NULL,
    blocked_count        INT         NOT NULL,
    confirmed_by         VARCHAR(64) NOT NULL,
    confirmed_at         TIMESTAMP   NOT NULL,
    confirmation_comment VARCHAR(500),
    failure_reason       VARCHAR(500),
    created_at           TIMESTAMP   NOT NULL,
    CONSTRAINT ck_sub_conv_status CHECK (status IN ('CONVERTED', 'FAILED')),
    CONSTRAINT fk_sub_conv_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);

-- 逐条留痕：转换前后实例日期与日期依据，保证原始历史可追溯、可审计。
CREATE TABLE substitution_conversion_item (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversion_id             BIGINT      NOT NULL,
    substitution_id           BIGINT      NOT NULL,
    entry_id                  BIGINT      NOT NULL,
    type                      VARCHAR(20) NOT NULL,
    lesson_date_before        DATE,
    target_lesson_date_before DATE,
    lesson_date_after         DATE,
    target_lesson_date_after  DATE,
    basis                     VARCHAR(500),
    CONSTRAINT fk_sub_conv_item_batch FOREIGN KEY (conversion_id)
        REFERENCES substitution_conversion (id) ON DELETE CASCADE
);

CREATE INDEX idx_sub_conv_semester ON substitution_conversion (semester_id, created_at);
CREATE INDEX idx_sub_conv_item_batch ON substitution_conversion_item (conversion_id);
