CREATE TABLE assignment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id       BIGINT    NOT NULL,
    admin_class_id    BIGINT    NOT NULL,
    teaching_class_id BIGINT    NOT NULL,
    course_id         BIGINT    NOT NULL,
    teacher_id        BIGINT    NOT NULL,
    weekly_lessons    INT       NOT NULL,
    created_at        TIMESTAMP NOT NULL,
    CONSTRAINT fk_assignment_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_class FOREIGN KEY (admin_class_id) REFERENCES admin_class (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_teaching FOREIGN KEY (teaching_class_id) REFERENCES teaching_class (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT fk_assignment_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (id),
    CONSTRAINT uk_assignment_class_course UNIQUE (semester_id, teaching_class_id, course_id)
);

CREATE INDEX idx_assignment_semester ON assignment (semester_id);
CREATE INDEX idx_assignment_teacher ON assignment (semester_id, teacher_id);
CREATE INDEX idx_assignment_class ON assignment (semester_id, admin_class_id);
