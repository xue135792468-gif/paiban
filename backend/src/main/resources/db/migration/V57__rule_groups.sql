-- 票 04：用户分组（教师组 / 课程组 / 时间组）。
--
-- 分组只是批量选择，不参与评估：规则参数里存 group id，快照构建时再展开成
-- 具体教师/课程/课节。这样改组成员后，引用该组的规则不改动也立即生效。
--
-- 唯一性用可移植的 live_key / member_key，不用 PostgreSQL 部分唯一索引
-- （H2 2.3 不支持 CREATE UNIQUE INDEX ... WHERE，本地测试会直接失败）：
--   * live_key 由服务层维护，软删除时置 NULL，恢复时重算；
--   * member_key 由服务层按成员类型写入，更新成员时整体替换。

CREATE TABLE rule_group (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_type  VARCHAR(16) NOT NULL,
    name        VARCHAR(64) NOT NULL,
    semester_id BIGINT      NULL,
    live_key    VARCHAR(160) NULL,
    created_at  TIMESTAMP   NOT NULL,
    updated_at  TIMESTAMP   NOT NULL,
    deleted_at  TIMESTAMP   NULL,
    CONSTRAINT fk_rule_group_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT ck_rule_group_type CHECK (group_type IN ('TEACHER','COURSE','TIME')),
    CONSTRAINT ck_rule_group_semester CHECK ((group_type = 'TIME') = (semester_id IS NOT NULL))
);

CREATE UNIQUE INDEX uq_rule_group_live_key ON rule_group (live_key);
CREATE INDEX idx_rule_group_type ON rule_group (group_type, deleted_at);
CREATE INDEX idx_rule_group_semester ON rule_group (semester_id);

CREATE TABLE rule_group_member (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id    BIGINT NOT NULL,
    member_key  VARCHAR(48) NOT NULL,
    teacher_id  BIGINT NULL,
    course_id   BIGINT NULL,
    day_of_week INT NULL,
    period_no   INT NULL,
    CONSTRAINT fk_rule_group_member_group FOREIGN KEY (group_id) REFERENCES rule_group (id) ON DELETE CASCADE,
    CONSTRAINT fk_rule_group_member_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (id),
    CONSTRAINT fk_rule_group_member_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT ck_rule_group_member_one CHECK (
        (CASE WHEN teacher_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN course_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN day_of_week IS NOT NULL AND period_no IS NOT NULL THEN 1 ELSE 0 END) = 1
    )
);

CREATE UNIQUE INDEX uq_rule_group_member_key ON rule_group_member (group_id, member_key);
CREATE INDEX idx_rule_group_member_group ON rule_group_member (group_id);
