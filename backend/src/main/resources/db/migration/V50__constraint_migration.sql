-- 票 11：旧 26 类约束配置迁移到 19 类语义。
--
-- 迁移不物理删除任何旧配置/条目：删除的 7 类只把 config 与 entry 的 enabled 置 false，
-- 旧行仍可查。每次运行写一条 run（含前后草稿校验快照），每一行旧配置/条目写一条 map，
-- 以 (semester_id, old_type, old_entry_id) 唯一，重复运行只 upsert，不产生重复条目。
-- config 级行用 old_entry_id = 0。

CREATE TABLE constraint_migration_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        VARCHAR(36)  NOT NULL UNIQUE,
    semester_id   BIGINT       NOT NULL,
    status        VARCHAR(16)  NOT NULL,
    started_at    TIMESTAMP    NOT NULL,
    finished_at   TIMESTAMP    NULL,
    run_by        VARCHAR(64)  NOT NULL,
    before_json   TEXT         NULL,
    after_json    TEXT         NULL,
    summary_json  TEXT         NULL
);

CREATE INDEX idx_constraint_migration_run_semester
    ON constraint_migration_run (semester_id, started_at);

CREATE TABLE constraint_migration_map (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          VARCHAR(36) NOT NULL,
    semester_id     BIGINT      NOT NULL,
    old_type        VARCHAR(64) NOT NULL,
    old_entry_id    BIGINT      NOT NULL DEFAULT 0,
    new_type        VARCHAR(64) NULL,
    action          VARCHAR(16) NOT NULL,
    group_key       VARCHAR(64) NULL,
    params_json     TEXT        NULL,
    note            VARCHAR(500) NULL,
    requires_review BOOLEAN     NOT NULL DEFAULT FALSE,
    migrated_at     TIMESTAMP   NOT NULL
);

CREATE UNIQUE INDEX uk_constraint_migration_map
    ON constraint_migration_map (semester_id, old_type, old_entry_id);
CREATE INDEX idx_constraint_migration_map_run
    ON constraint_migration_map (run_id);
