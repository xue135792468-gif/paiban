-- Ticket 03: one row per AI import session, from preview through commit.
CREATE TABLE ai_import_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT,
    username        VARCHAR(64),
    import_type     VARCHAR(20)  NOT NULL,
    target_type     VARCHAR(30)  NOT NULL,
    file_name       VARCHAR(255),
    file_size       BIGINT,
    file_path       VARCHAR(500),
    source_text     TEXT,
    preview_json    TEXT,
    confirmed_json  TEXT,
    result_json     TEXT,
    ai_explanation  TEXT,
    ai_raw_response TEXT,
    status          VARCHAR(20)  NOT NULL,
    row_count       INT          NOT NULL DEFAULT 0,
    imported_count  INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL
);

CREATE INDEX idx_ai_import_log_created_at ON ai_import_log (created_at);
CREATE INDEX idx_ai_import_log_user_id ON ai_import_log (user_id);
CREATE INDEX idx_ai_import_log_status ON ai_import_log (status);
