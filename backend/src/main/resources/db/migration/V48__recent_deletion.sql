-- 票 03：核心数据软删除 + 停用 + 7 天“最近删除”。
--
-- 删除一律是软删除：行还在库里，草稿/规则里的 id 仍能解析，不会凭空 500；
-- 停用只改 active，管理列表仍显示，下拉选项排除。最近删除按 batch_id 归组，
-- 同一次“一起删”产生一个批次，恢复时整批回来。

ALTER TABLE teacher ADD COLUMN deleted_at TIMESTAMP NULL;

ALTER TABLE admin_class ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE admin_class ADD COLUMN deleted_at TIMESTAMP NULL;

ALTER TABLE course ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE course ADD COLUMN deleted_at TIMESTAMP NULL;

ALTER TABLE grade ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE grade ADD COLUMN deleted_at TIMESTAMP NULL;

ALTER TABLE semester ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE semester ADD COLUMN deleted_at TIMESTAMP NULL;

ALTER TABLE assignment ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE assignment ADD COLUMN deleted_at TIMESTAMP NULL;

CREATE TABLE recent_deletion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id     VARCHAR(36)  NOT NULL,
    entity_type  VARCHAR(32)  NOT NULL,
    entity_id    BIGINT       NOT NULL,
    entity_label VARCHAR(255) NOT NULL,
    primary_flag BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_by   VARCHAR(64)  NOT NULL,
    deleted_at   TIMESTAMP    NOT NULL,
    expires_at   TIMESTAMP    NOT NULL,
    restored_at  TIMESTAMP    NULL,
    restored_by  VARCHAR(64)  NULL
);

CREATE INDEX idx_recent_deletion_batch ON recent_deletion (batch_id);
CREATE INDEX idx_recent_deletion_expires ON recent_deletion (expires_at);
CREATE INDEX idx_recent_deletion_entity ON recent_deletion (entity_type, entity_id);

CREATE INDEX idx_teacher_deleted ON teacher (deleted_at);
CREATE INDEX idx_class_deleted ON admin_class (deleted_at);
CREATE INDEX idx_course_deleted ON course (deleted_at);
CREATE INDEX idx_grade_deleted ON grade (deleted_at);
CREATE INDEX idx_semester_deleted ON semester (deleted_at);
CREATE INDEX idx_assignment_deleted ON assignment (deleted_at);
