-- Natural-language constraint generation runs (ticket 14/08).
--
-- One row per user trigger. It is the run identity that makes a retry of the same
-- click idempotent, the business record that keeps the user's original text, the full
-- raw model answer and the normalized proposals separately, and the audit row for
-- cancelled/failed/timed-out calls. It is deliberately not `ai_call_log`: the generic
-- log truncates its payload and must not stand in for a complete business record.
CREATE TABLE constraint_generation_run (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_run_id   VARCHAR(64)  NOT NULL,
    user_id         BIGINT,
    semester_id     BIGINT       NOT NULL,
    task_type       VARCHAR(50)  NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    input_text      TEXT         NOT NULL,
    context_json    TEXT,
    raw_response    TEXT,
    late_response   TEXT,
    proposals_json  TEXT,
    error_code      VARCHAR(50),
    error_message   VARCHAR(1000),
    provider_name   VARCHAR(200),
    model_name      VARCHAR(200),
    input_tokens    INT,
    output_tokens   INT,
    latency_ms      BIGINT,
    started_at      TIMESTAMP    NOT NULL,
    finished_at     TIMESTAMP,
    CONSTRAINT fk_generation_run_semester
        FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT uq_generation_run_client UNIQUE (user_id, client_run_id)
);

CREATE INDEX idx_generation_run_user_semester
    ON constraint_generation_run (user_id, semester_id, started_at);
