CREATE TABLE timetable_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id    BIGINT    NOT NULL,
    draft_id       BIGINT    NOT NULL,
    admin_class_id BIGINT    NOT NULL,
    course_id      BIGINT    NOT NULL,
    teacher_id     BIGINT    NOT NULL,
    room_id        BIGINT,
    period_id      BIGINT    NOT NULL,
    day_of_week    INT       NOT NULL,
    period_no      INT       NOT NULL,
    created_at     TIMESTAMP NOT NULL,
    CONSTRAINT fk_entry_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_entry_class FOREIGN KEY (admin_class_id) REFERENCES admin_class (id) ON DELETE CASCADE,
    CONSTRAINT fk_entry_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT fk_entry_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (id),
    CONSTRAINT fk_entry_period FOREIGN KEY (period_id) REFERENCES period (id)
);

CREATE TABLE timetable_publish (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id  BIGINT      NOT NULL,
    draft_id     BIGINT      NOT NULL,
    published_by VARCHAR(64),
    published_at TIMESTAMP   NOT NULL,
    CONSTRAINT fk_publish_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);

CREATE INDEX idx_entry_semester ON timetable_entry (semester_id);
CREATE INDEX idx_entry_class ON timetable_entry (semester_id, admin_class_id);
CREATE INDEX idx_entry_teacher ON timetable_entry (semester_id, teacher_id);
CREATE INDEX idx_entry_room ON timetable_entry (semester_id, room_id);
CREATE INDEX idx_publish_semester ON timetable_publish (semester_id, published_at);
