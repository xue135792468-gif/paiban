-- Multiple parameter entries per constraint type (ADR-0028).
--
-- The type-level row keeps enabled/hard/weight and stays unique per
-- (semester, type); each editable parameter set becomes its own row with a stable
-- id. Existing single-params configurations are copied as one legacy entry so an
-- upgraded semester means exactly what it meant before. `{}` carries no object
-- condition, so it is not copied: the settings snapshot synthesises "no entries"
-- for it, which is the same verdict as the old empty params.
CREATE TABLE constraint_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT        NOT NULL,
    type        VARCHAR(64)   NOT NULL,
    params_json VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL,
    CONSTRAINT fk_constraint_entry_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);

CREATE INDEX idx_constraint_entry_semester_type ON constraint_entry (semester_id, type);

INSERT INTO constraint_entry (semester_id, type, params_json, created_at)
SELECT semester_id, type, params_json, CURRENT_TIMESTAMP
FROM constraint_config
WHERE params_json IS NOT NULL
  AND TRIM(params_json) <> ''
  AND TRIM(params_json) <> '{}';
