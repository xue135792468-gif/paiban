CREATE TABLE constraint_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT      NOT NULL,
    type        VARCHAR(64) NOT NULL,
    params_json VARCHAR(4000),
    weight      INT         NOT NULL DEFAULT 50,
    hard        BOOLEAN     NOT NULL DEFAULT FALSE,
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_constraint_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT uk_constraint_semester_type UNIQUE (semester_id, type)
);

CREATE TABLE constraint_template (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    configs_json VARCHAR(8000) NOT NULL,
    created_at   TIMESTAMP    NOT NULL
);

CREATE INDEX idx_constraint_semester ON constraint_config (semester_id);
