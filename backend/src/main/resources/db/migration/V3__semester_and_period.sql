CREATE TABLE semester (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    start_date  DATE         NOT NULL,
    end_date    DATE         NOT NULL,
    is_current  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE period (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT      NOT NULL,
    day_of_week INT         NOT NULL,
    period_no   INT         NOT NULL,
    label       VARCHAR(50) NOT NULL,
    section     VARCHAR(20) NOT NULL,
    start_time  TIME        NOT NULL,
    end_time    TIME        NOT NULL,
    CONSTRAINT fk_period_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT uk_period_slot UNIQUE (semester_id, day_of_week, period_no)
);

CREATE INDEX idx_period_semester ON period (semester_id);
CREATE INDEX idx_period_semester_day ON period (semester_id, day_of_week, period_no);
