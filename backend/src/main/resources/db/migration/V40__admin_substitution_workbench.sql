-- 票 03（管理员调代工作台）：预览凭证 + 管理代发的审计字段。

-- 预览凭证：绑定操作者、来源实例、整份快照哈希、选定代课人与过期时间。
-- 是可保存的短期试算结果，不是待审批申请：创建/消费它零申请、零生效、零通知。
-- 幂等：同一凭证相同动作 + 相同参数的重试返回第一次结果（result_json）；
-- 参数改变不复用已消费凭证（action_hash 不一致时返回冲突）。
CREATE TABLE substitution_preview (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id            BIGINT       NOT NULL,
    entry_id               BIGINT       NOT NULL,
    lesson_date            DATE         NOT NULL,
    substitute_teacher_id  BIGINT       NOT NULL,
    previous_teacher_id    BIGINT       NOT NULL,
    operator_user_id       BIGINT       NOT NULL,
    snapshot_hash          VARCHAR(64)  NOT NULL,
    status                 VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    action_type            VARCHAR(20),
    action_hash            VARCHAR(64),
    result_json            VARCHAR(2000),
    reason                 VARCHAR(500),
    deadline_at            TIMESTAMP    NOT NULL,
    expires_at             TIMESTAMP    NOT NULL,
    created_at             TIMESTAMP    NOT NULL,
    consumed_at            TIMESTAMP,
    CONSTRAINT fk_preview_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_preview_entry FOREIGN KEY (entry_id) REFERENCES timetable_entry (id) ON DELETE CASCADE
);

CREATE INDEX idx_preview_entry_date ON substitution_preview (entry_id, lesson_date, status);
CREATE INDEX idx_preview_operator ON substitution_preview (operator_user_id, status);

-- 管理代发的审计字段（规格第 1 节）：申请要分别保存
-- 真实操作账号、代发对象（requester_teacher_id 沿用）、基线原教师（original_teacher_id 沿用）、
-- 调整前教师、调整后教师与审批人（approver_id 沿用）；
-- 管理员绑定的教师身份不得顶替这些信息。
ALTER TABLE substitution_request ADD COLUMN operator_user_id BIGINT;
ALTER TABLE substitution_request ADD COLUMN previous_teacher_id BIGINT;
ALTER TABLE substitution_request ADD COLUMN final_teacher_id BIGINT;
