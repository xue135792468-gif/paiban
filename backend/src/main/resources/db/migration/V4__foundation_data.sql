CREATE TABLE teacher (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL,
    employee_no      VARCHAR(50),
    phone            VARCHAR(30),
    email            VARCHAR(120),
    subject          VARCHAR(100),
    dingtalk_user_id VARCHAR(100),
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT uk_teacher_employee_no UNIQUE (employee_no)
);

CREATE TABLE room (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    capacity   INT          NOT NULL DEFAULT 50,
    type       VARCHAR(50)  NOT NULL DEFAULT 'NORMAL',
    building   VARCHAR(100),
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT uk_room_name UNIQUE (name)
);

CREATE TABLE course (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL,
    subject            VARCHAR(100),
    allow_consecutive  BOOLEAN      NOT NULL DEFAULT FALSE,
    require_outdoor    BOOLEAN      NOT NULL DEFAULT FALSE,
    required_room_type VARCHAR(50),
    color              VARCHAR(20),
    created_at         TIMESTAMP    NOT NULL,
    CONSTRAINT uk_course_name UNIQUE (name)
);

CREATE TABLE grade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    CONSTRAINT fk_grade_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT uk_grade_semester_name UNIQUE (semester_id, name)
);

CREATE TABLE admin_class (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id     BIGINT       NOT NULL,
    grade_id        BIGINT       NOT NULL,
    name            VARCHAR(100) NOT NULL,
    head_teacher_id BIGINT,
    student_count   INT          NOT NULL DEFAULT 45,
    CONSTRAINT fk_class_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_class_grade FOREIGN KEY (grade_id) REFERENCES grade (id) ON DELETE CASCADE,
    CONSTRAINT fk_class_head_teacher FOREIGN KEY (head_teacher_id) REFERENCES teacher (id) ON DELETE SET NULL,
    CONSTRAINT uk_class_semester_name UNIQUE (semester_id, name)
);

CREATE TABLE teaching_class (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id    BIGINT       NOT NULL,
    admin_class_id BIGINT       NOT NULL,
    name           VARCHAR(100) NOT NULL,
    CONSTRAINT fk_teaching_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_teaching_admin_class FOREIGN KEY (admin_class_id) REFERENCES admin_class (id) ON DELETE CASCADE,
    CONSTRAINT uk_teaching_admin_class UNIQUE (admin_class_id)
);

CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor        VARCHAR(64)  NOT NULL,
    action       VARCHAR(100) NOT NULL,
    entity_type  VARCHAR(50)  NOT NULL,
    detail       VARCHAR(1000),
    success_rows INT          NOT NULL DEFAULT 0,
    failed_rows  INT          NOT NULL DEFAULT 0,
    created_at   TIMESTAMP    NOT NULL
);

CREATE INDEX idx_grade_semester ON grade (semester_id);
CREATE INDEX idx_class_semester ON admin_class (semester_id);
CREATE INDEX idx_class_grade ON admin_class (grade_id);
CREATE INDEX idx_teaching_semester ON teaching_class (semester_id);
CREATE INDEX idx_audit_created ON audit_log (created_at);
