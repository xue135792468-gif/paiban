CREATE TABLE substitution_request (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id                   BIGINT       NOT NULL,
    entry_id                      BIGINT       NOT NULL,
    admin_class_id                BIGINT       NOT NULL,
    course_id                     BIGINT       NOT NULL,
    original_teacher_id           BIGINT       NOT NULL,
    requester_teacher_id          BIGINT,
    effective_date                DATE         NOT NULL,
    period_id                     BIGINT       NOT NULL,
    day_of_week                   INT          NOT NULL,
    period_no                     INT          NOT NULL,
    reason                        VARCHAR(500),
    expected_substitute_teacher_id BIGINT,
    status                        VARCHAR(30)  NOT NULL,
    approval_mode                 VARCHAR(20)  NOT NULL,
    approver_id                   BIGINT,
    approved_at                   TIMESTAMP,
    approval_comment              VARCHAR(500),
    created_at                    TIMESTAMP    NOT NULL,
    updated_at                    TIMESTAMP    NOT NULL,
    CONSTRAINT fk_sub_req_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_req_entry FOREIGN KEY (entry_id) REFERENCES timetable_entry (id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_req_class FOREIGN KEY (admin_class_id) REFERENCES admin_class (id) ON DELETE CASCADE
);

CREATE TABLE substitution_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT      NOT NULL,
    from_status VARCHAR(30),
    to_status   VARCHAR(30) NOT NULL,
    actor      VARCHAR(64),
    comment    VARCHAR(500),
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT fk_sub_hist_request FOREIGN KEY (request_id) REFERENCES substitution_request (id) ON DELETE CASCADE
);

CREATE TABLE substitution (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id            BIGINT    NOT NULL,
    request_id             BIGINT    NOT NULL,
    entry_id               BIGINT    NOT NULL,
    effective_date         DATE      NOT NULL,
    original_teacher_id    BIGINT    NOT NULL,
    substitute_teacher_id  BIGINT    NOT NULL,
    new_room_id            BIGINT,
    new_period_id          BIGINT,
    new_day_of_week        INT,
    new_period_no          INT,
    status                 VARCHAR(20) NOT NULL DEFAULT 'EFFECTIVE',
    created_at             TIMESTAMP NOT NULL,
    CONSTRAINT fk_sub_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_request FOREIGN KEY (request_id) REFERENCES substitution_request (id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_entry FOREIGN KEY (entry_id) REFERENCES timetable_entry (id) ON DELETE CASCADE
);

CREATE INDEX idx_sub_req_semester ON substitution_request (semester_id, status);
CREATE INDEX idx_sub_req_requester ON substitution_request (requester_teacher_id);
CREATE INDEX idx_sub_hist_request ON substitution_history (request_id);
CREATE INDEX idx_sub_entry_date ON substitution (entry_id, effective_date);
CREATE INDEX idx_sub_semester_date ON substitution (semester_id, effective_date);
CREATE INDEX idx_sub_substitute ON substitution (substitute_teacher_id, effective_date);
