CREATE TABLE timetable_draft (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    score_hard  INT          NOT NULL DEFAULT 0,
    score_soft  INT          NOT NULL DEFAULT 0,
    created_by  VARCHAR(64),
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_draft_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);

CREATE TABLE draft_lesson (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id       BIGINT NOT NULL,
    assignment_id  BIGINT NOT NULL,
    lesson_index   INT    NOT NULL,
    course_id      BIGINT NOT NULL,
    teacher_id     BIGINT NOT NULL,
    admin_class_id BIGINT NOT NULL,
    student_count  INT    NOT NULL DEFAULT 45,
    period_id      BIGINT,
    room_id        BIGINT,
    CONSTRAINT fk_lesson_draft FOREIGN KEY (draft_id) REFERENCES timetable_draft (id) ON DELETE CASCADE
);

CREATE TABLE scheduling_job (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id   BIGINT      NOT NULL,
    status        VARCHAR(20) NOT NULL,
    score         VARCHAR(50),
    progress      INT         NOT NULL DEFAULT 0,
    elapsed_ms    BIGINT      NOT NULL DEFAULT 0,
    error_message VARCHAR(2000),
    draft_id      BIGINT,
    draft_name    VARCHAR(100),
    solve_seconds INT         NOT NULL DEFAULT 60,
    created_by    VARCHAR(64),
    created_at    TIMESTAMP   NOT NULL,
    started_at    TIMESTAMP,
    finished_at   TIMESTAMP,
    CONSTRAINT fk_job_semester FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);

CREATE INDEX idx_draft_semester ON timetable_draft (semester_id);
CREATE INDEX idx_draft_lesson_draft ON draft_lesson (draft_id);
CREATE INDEX idx_job_semester_status ON scheduling_job (semester_id, status);
