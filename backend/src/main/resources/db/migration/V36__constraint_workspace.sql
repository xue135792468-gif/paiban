-- Unsaved constraint work per account and semester (ticket 14/11).
--
-- One row per (user, semester). `revision` is the workspace's own counter: an autosave
-- names the revision it started from, so two devices of the same account cannot silently
-- overwrite each other. The row never changes the effective configuration; a successful
-- save deletes it so a stale draft cannot be restored afterwards.
CREATE TABLE constraint_workspace (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT    NOT NULL,
    semester_id  BIGINT    NOT NULL,
    revision     BIGINT    NOT NULL,
    base_version BIGINT    NOT NULL,
    payload_json TEXT      NOT NULL,
    updated_at   TIMESTAMP NOT NULL,
    CONSTRAINT uq_constraint_workspace UNIQUE (user_id, semester_id),
    CONSTRAINT fk_constraint_workspace_semester
        FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE
);
