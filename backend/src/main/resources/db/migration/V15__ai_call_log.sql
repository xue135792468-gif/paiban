-- Ticket 02: one row per AI gateway call (success or failure).
CREATE TABLE ai_call_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type      VARCHAR(50)  NOT NULL,
    provider_id    BIGINT,
    provider_name  VARCHAR(100),
    model_id       BIGINT,
    model_name     VARCHAR(200),
    user_id        BIGINT,
    subject_type   VARCHAR(50),
    subject_id     BIGINT,
    success        BOOLEAN      NOT NULL,
    error_code     VARCHAR(50),
    error_message  VARCHAR(1000),
    input_tokens   INTEGER,
    output_tokens  INTEGER,
    latency_ms     BIGINT,
    request_json   TEXT,
    response_json  TEXT,
    created_at     TIMESTAMP    NOT NULL
);

CREATE INDEX idx_ai_call_log_created_at ON ai_call_log (created_at);
CREATE INDEX idx_ai_call_log_task_type ON ai_call_log (task_type);
CREATE INDEX idx_ai_call_log_user_id ON ai_call_log (user_id);
