-- Confirmation audit for effective-configuration saves (ticket 14/10).
--
-- The row keeps the exact final configuration plus the user's decisions about the
-- proposals (added / replaced / skipped / already existed). Together with the run's
-- raw answer it lets an auditor see the original words, the model answer, the manual
-- choices and the final change — none of it reconstructed afterwards from whatever the
-- configuration happens to be now.
CREATE TABLE constraint_save_audit (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id       BIGINT       NOT NULL,
    version           BIGINT       NOT NULL,
    user_id           BIGINT,
    actor             VARCHAR(100),
    run_id            BIGINT,
    decisions_json    TEXT,
    final_config_json TEXT         NOT NULL,
    created_at        TIMESTAMP    NOT NULL,
    CONSTRAINT fk_save_audit_semester
        FOREIGN KEY (semester_id) REFERENCES semester (id) ON DELETE CASCADE,
    CONSTRAINT fk_save_audit_run
        FOREIGN KEY (run_id) REFERENCES constraint_generation_run (id) ON DELETE SET NULL
);

CREATE INDEX idx_save_audit_semester ON constraint_save_audit (semester_id, created_at);
CREATE INDEX idx_save_audit_run ON constraint_save_audit (run_id);
