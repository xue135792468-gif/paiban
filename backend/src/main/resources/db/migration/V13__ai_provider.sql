CREATE TABLE ai_provider (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    type           VARCHAR(20)  NOT NULL,
    base_url       VARCHAR(500) NOT NULL,
    api_key_cipher VARCHAR(1000),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    CONSTRAINT uk_ai_provider_name UNIQUE (name)
);

CREATE TABLE ai_model (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id    BIGINT       NOT NULL,
    model_name     VARCHAR(200) NOT NULL,
    display_name   VARCHAR(200) NOT NULL,
    vision_capable BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    params_json    VARCHAR(4000),
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT fk_ai_model_provider FOREIGN KEY (provider_id) REFERENCES ai_provider (id) ON DELETE CASCADE,
    CONSTRAINT uk_ai_model_provider_name UNIQUE (provider_id, model_name)
);

CREATE TABLE ai_task_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type   VARCHAR(50) NOT NULL,
    mode        VARCHAR(20) NOT NULL,
    provider_id BIGINT,
    model_id    BIGINT,
    updated_at  TIMESTAMP   NOT NULL,
    CONSTRAINT uk_ai_task_config_task UNIQUE (task_type),
    CONSTRAINT fk_ai_task_provider FOREIGN KEY (provider_id) REFERENCES ai_provider (id) ON DELETE SET NULL,
    CONSTRAINT fk_ai_task_model FOREIGN KEY (model_id) REFERENCES ai_model (id) ON DELETE SET NULL
);

CREATE INDEX idx_ai_model_provider ON ai_model (provider_id);
CREATE INDEX idx_ai_task_provider ON ai_task_config (provider_id);
CREATE INDEX idx_ai_task_model ON ai_task_config (model_id);
